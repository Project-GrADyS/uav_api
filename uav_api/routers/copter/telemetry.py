@router.get("/compass", tags=["telemetry"], summary="Returns compass calibration information", response_model=CompassTelemetryResponse, responses=error_responses({404: "No MAG_CAL_REPORT received yet — the message is only emitted during a compass calibration (never in SITL).", 500: "The underlying MAVLink command failed or timed out; detail carries the cause."}))
def compass_info(uav: Copter = Depends(get_copter_instance), args: Namespace = Depends(get_args)):
    try:
        info = uav.get_compass_info()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"GET_COMPASS_INFO FAIL: {e}")
    if info is None:
        raise HTTPException(status_code=404, detail="No compass calibration report received (MAG_CAL_REPORT is only emitted during a compass calibration)")
    try:
        res_obj = {
            "device": "uav",
            "id": str(args.sysid),
            "result": "success",
            "info": {
                "calibration_status": info.calibration_status,
                "autosaved": bool(info.autosaved),
                "fitness": {
                    "x": info.fitness[0],
                    "y": info.fitness[1],
                    "z": info.fitness[2]
                }
            }
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"GET_COMPASS_INFO FAIL: {e}")

    return res_obj
@router.get("/sys_status", tags=["telemetry"], summary="Returns raw SYS_STATUS message", response_model=SysStatusResponse, responses=COMMAND_FAILED)
def sys_status(uav: Copter = Depends(get_copter_instance), args: Namespace = Depends(get_args)):
    """Unprocessed SYS_STATUS as a dict; values keep MAVLink's native units
    (mV, cA, c%). Prefer /telemetry/sensor_status, /telemetry/battery_info and
    /telemetry/error_info for the parsed views."""
    try:
        status_message = uav.get_raw_status_message()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"GET_RAW_SYS_STATUS FAIL: {e}")
    return {"device": "uav", "id": str(args.sysid), "result": "success", "status": status_message.to_dict()}

