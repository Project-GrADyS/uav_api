from fastapi import APIRouter, Depends, HTTPException
from uav_api.vehicles.copter import Copter
from uav_api.classes.responses import (
    COMMAND_FAILED,
    error_responses,
    BatteryInfoResponse,
    CompassTelemetryResponse,
    ErrorInfoResponse,
    GeneralTelemetryResponse,
    GpsTelemetryResponse,
    HomeInfoResponse,
    NedTelemetryResponse,
    RawGpsTelemetryResponse,
    SensorStatusResponse,
    SysStatusResponse,
)
from uav_api.routers.dependencies import get_copter_instance, get_args
from argparse import Namespace
router = APIRouter(
    prefix="/telemetry",
    tags=["telemetry"],
)

@router.get("/general", tags=["telemetry"], summary="Returns Copter general information such as velocities, heading, throttle percentage and altitude", response_model=GeneralTelemetryResponse, responses=COMMAND_FAILED)
def general_info(uav: Copter = Depends(get_copter_instance), args: Namespace = Depends(get_args)):
    """Sourced from the VFR_HUD MAVLink message: speeds in m/s, heading in
    degrees, throttle in percent, altitude in meters (MSL)."""
    try:
        info = uav.get_general_info()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"GET_GENERAL_INFO FAIL: {e}")
    return {
        "device": "uav",
        "id": str(args.sysid),
        "result": "success",
        "info": {
            "airspeed": info.airspeed,
            "groundspeed": info.groundspeed,
            "heading": info.heading,
            "throttle": info.throttle,
            "alt": info.alt
        }
    }

@router.get("/gps", tags=["telemetry"], summary="Returns the copter current GPS information (the information provided by this endpoint is generated by the fusion of multiple sensor data such as GPS and accelerometers)", response_model=GpsTelemetryResponse, responses=COMMAND_FAILED)
def gps_info(uav: Copter = Depends(get_copter_instance), args: Namespace = Depends(get_args)):
    """Sourced from GLOBAL_POSITION_INT, converted to friendly units: lat/lon
    in degrees, altitudes in meters (relative_alt is above HOME), velocities in
    m/s, heading in degrees."""
    try:
        info = uav.get_gps_info()
        res_obj = {
            "device": "uav",
            "id": str(args.sysid),
            "result": "success", 
            "info": {
                "position": {
                    "lat": info.lat / 1.0e7, # to degrees
                    "lon": info.lon / 1.0e7, # to degrees
                    "alt": info.alt / 1000, # to meters
                    "relative_alt": info.relative_alt / 1000, # to meters
                },
                "velocity": {
                    "vx": info.vx / 100, # to meters per second
                    "vy": info.vy / 100, # to meters per second
                    "vz": info.vz / 100, # to meters per second
                },
                "heading": info.hdg / 100 # to degrees
            }
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"GET_GPS_POSITION FAIL: {e}")
    return res_obj

