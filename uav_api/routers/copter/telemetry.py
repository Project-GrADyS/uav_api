@router.get("/home_info", tags=["telemetry"], summary="Returns information about HOME position, which represents the point (0,0,0) in static NED coordinate frame", response_model=HomeInfoResponse, responses=COMMAND_FAILED)
def home_info(uav: Copter = Depends(get_copter_instance), args: Namespace = Depends(get_args)):
    """Lat/lon in degrees, altitude in meters (MSL). Unlike other telemetry
    endpoints, the fields sit directly on the envelope instead of nesting
    under 'info' (historical wire contract)."""
    try:
        info = uav.get_home_position()
        res_obj = {
            "device": "uav",
            "id": str(args.sysid),
            "result": "success", 
            "lat": info["latitude"] / 1.0e7, # to degrees
            "lon": info["longitude"] / 1.0e7, # to degrees
            "altitude": info["altitude"] / 1000, # to meters
            "x": info["x"],
            "y": info["y"],
            "z": info["z"]
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"GET_HOME_INFO FAIL: {e}")
    return res_obj